if ("IntersectionObserver" in window) {
  /* Scroll reveals, once */
  var revealObserver = new IntersectionObserver(function (entries) {
    entries.forEach(function (e) {
      if (e.isIntersecting) {
        e.target.classList.add("in");
        revealObserver.unobserve(e.target);
      }
    });
  }, { threshold: 0.08, rootMargin: "0px 0px -6% 0px" });
  qsa(".reveal").forEach(function (el) { revealObserver.observe(el); });

  /* Pinned stage: the sentinel that crosses the middle of the screen names the step */
  var pinObserver = new IntersectionObserver(function (entries) {
    entries.forEach(function (e) {
      if (e.isIntersecting && wideScreen.matches) setStep(e.target.getAttribute("data-s"));
    });
  }, { rootMargin: "-50% 0px -50% 0px" });
  qsa(".sentinel").forEach(function (el) { pinObserver.observe(el); });
  new IntersectionObserver(function (entries) {
    entries.forEach(function (e) {
      if (e.isIntersecting && wideScreen.matches) play(stage.getAttribute("data-step"));
    });
  }, { threshold: 0.35 }).observe(stage);
  /* Stacked cards: each demo plays when it is on screen */
  var cardObserver = new IntersectionObserver(function (entries) {
    entries.forEach(function (e) {
      if (e.isIntersecting && !wideScreen.matches) play(e.target.parentNode.getAttribute("data-step"));
    });
  }, { threshold: 0.3 });
  qsa(".way-demo").forEach(function (el) { cardObserver.observe(el); });

  /* Current section in the nav */
  var navLinks = qsa(".nav-links a");
  var navObserver = new IntersectionObserver(function (entries) {
    entries.forEach(function (e) {
      if (!e.isIntersecting) return;
      navLinks.forEach(function (a) {
        if (a.getAttribute("href") === "#" + e.target.getAttribute("data-nav")) a.setAttribute("aria-current", "true");
        else a.removeAttribute("aria-current");
      });
    });
  }, { rootMargin: "-40% 0px -55% 0px" });
  qsa("[data-nav]").forEach(function (el) { navObserver.observe(el); });

  /* If the tagline is jumped over (anchor link), light it all */
  var taglineSec = document.getElementById("tagline-sec");
  new IntersectionObserver(function (entries) {
    entries.forEach(function (e) {
      if (!e.isIntersecting && e.boundingClientRect.top < 0) qsa("#tagline .w").forEach(function (w) { w.classList.add("on"); });
    });
  }).observe(taglineSec);
} else {
  qsa(".reveal").forEach(function (el) { el.classList.add("in"); });
  ORDER.forEach(play);
}

function splitTagline() {
  var box = document.querySelector("#tagline .tl-words");
  if (!box) return;
  if (wordObserver) wordObserver.disconnect();
  box.textContent = "";
  tr("tagline").split(/\s+/).forEach(function (w) {
    var s = document.createElement("span");
    s.className = "w";
    s.textContent = w;
    box.appendChild(s);
    box.appendChild(document.createTextNode(" "));
  });
  var words = qsa(".w", box);
  if (reduceMotion || !("IntersectionObserver" in window)) {
    words.forEach(function (w) { w.classList.add("on"); });
    return;
  }
  /* each word lights up when it crosses a line at 65% of the viewport height */
  wordObserver = new IntersectionObserver(function (entries) {
    var k = 0;
    entries.forEach(function (e) {
      if (!e.isIntersecting) return;
      e.target.style.transitionDelay = (k++ * 70) + "ms";
      e.target.classList.add("on");
      wordObserver.unobserve(e.target);
    });
  }, { rootMargin: "0px 0px -35% 0px" });
  words.forEach(function (w) { wordObserver.observe(w); });
}
function splitHeard() {
  var el = document.getElementById("heard");
  if (!el) return;
  var n = 0;
  qsa("*", el).forEach(function (m) { m.classList.add("w"); });
  Array.prototype.slice.call(el.childNodes).forEach(function (node) {
    if (node.nodeType !== 3) { node.style.setProperty("--n", n++); return; }
    var frag = document.createDocumentFragment();
    node.textContent.split(/(\s+)/).forEach(function (part) {
      if (!part) return;
      if (/^\s+$/.test(part)) { frag.appendChild(document.createTextNode(part)); return; }
      var s = document.createElement("span");
      s.className = "w";
      s.style.setProperty("--n", n++);
      s.textContent = part;
      frag.appendChild(s);
    });
    el.replaceChild(frag, node);
  });
}

/* Language: ?lang= wins, then the saved choice, then English. Always run once so inline English cannot drift. */
var initialLang = "en";
try {
  var saved = localStorage.getItem("lang");
  if (saved && T[saved]) initialLang = saved;
} catch (e) {}
try {
  var asked = new URLSearchParams(window.location.search).get("lang");
  if (asked && T[asked]) {
    initialLang = asked;
    /* a translated URL is its own page for search engines */
    var canon = document.querySelector('link[rel="canonical"]');
    if (canon && asked !== "en") canon.href = "https://ceruapp.com/?lang=" + asked;
  }
} catch (e) {}
setLang(initialLang);
qsa(".lang-btn").forEach(function (b) {
  b.addEventListener("click", function () { setLang(b.getAttribute("data-lang")); });
});

/* Mobile menu */
var menu = document.getElementById("mobileMenu");
var navToggle = document.getElementById("navToggle");
function openMenu() {
  menu.classList.add("open");
  navToggle.setAttribute("aria-expanded", "true");
  document.body.style.overflow = "hidden";
}
function closeMenu() {
  menu.classList.remove("open");
  navToggle.setAttribute("aria-expanded", "false");
  document.body.style.overflow = "";
}
function toggleMenu() {
  if (menu.classList.contains("open")) closeMenu(); else openMenu();
}
navToggle.addEventListener("click", toggleMenu);
qsa("#mobileMenu a").forEach(function (a) { a.addEventListener("click", closeMenu); });
document.addEventListener("keydown", function (e) {
  if (e.key !== "Escape") return;
  closeMenu();
});
var wideScreen = window.matchMedia("(min-width: 1024px)");
function syncMenuToBreakpoint(e) { if (e.matches) closeMenu(); }
if (wideScreen.addEventListener) wideScreen.addEventListener("change", syncMenuToBreakpoint);
else wideScreen.addListener(syncMenuToBreakpoint);

/* Split type control: the same bill, torn three ways */
var pieces = document.getElementById("pieces");
var splitSeg = document.getElementById("splitSeg");
var MODES = ["equal", "exact", "shares"];
qsa(".seg-btn", splitSeg).forEach(function (b) {
  b.addEventListener("click", function () {
    var mode = b.getAttribute("data-mode");
    if (pieces.getAttribute("data-mode") === mode) return;
    pieces.setAttribute("data-mode", mode);
    splitSeg.querySelector(".seg-thumb").style.setProperty("--i", MODES.indexOf(mode));
    qsa(".seg-btn", splitSeg).forEach(function (x) { x.setAttribute("aria-pressed", x === b ? "true" : "false"); });
    pieces.classList.remove("swap");
    void pieces.offsetWidth;
    pieces.classList.add("swap");
  });
});

/* The stage: one device, three demos. Each demo plays once. */
var stage = document.querySelector(".stage");
var track = document.querySelector(".stage-track");
var ORDER = ["voice", "scan", "type"];
function typeInto(el, delay, done) {
  var text = el.getAttribute("data-type"), holder = el.parentNode;
  el.textContent = "";
  setTimeout(function () {
    holder.classList.add("typing");
    var i = 0;
    (function next() {
      el.textContent = text.slice(0, ++i);
      if (i < text.length) setTimeout(next, 90);
      else { holder.classList.remove("typing"); if (done) done(); }
    })();
  }, delay);
}
function play(step) {
  var way = stage.querySelector('.way[data-step="' + step + '"]');
  if (!way || way.classList.contains("played")) return;
  way.classList.add("played");
  if (step !== "type") return;
  var fields = qsa("[data-type]", way);
  var typedOut = function () {
    way.classList.add("is-typed");
    setTimeout(function () { way.classList.add("synced"); }, reduceMotion ? 0 : 1600);
  };
  if (reduceMotion || !wideScreen.matches) { typedOut(); return; }
  typeInto(fields[0], 500, function () { typeInto(fields[1], 200, typedOut); });
}
function setStep(step) {
  stage.setAttribute("data-step", step);
  qsa(".stage-tabs .seg-btn").forEach(function (t) { t.setAttribute("aria-pressed", t.getAttribute("data-go") === step ? "true" : "false"); });
  play(step);
}
qsa(".stage-tabs .seg-btn").forEach(function (t) {
  t.addEventListener("click", function () {
    var n = ORDER.indexOf(t.getAttribute("data-go")), vh = window.innerHeight;
    var pin = parseFloat(getComputedStyle(document.querySelector(".stage-slab")).top) || 88;
    var top = track.getBoundingClientRect().top + window.pageYOffset + (n === 0 ? 8 - pin : vh * (0.3 + n * 0.6) - 88);
    window.scrollTo({ top: top, behavior: reduceMotion ? "auto" : "smooth" });
  });
});

